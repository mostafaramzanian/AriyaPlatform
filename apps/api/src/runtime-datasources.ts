export function ownerOf(datasource: Datasource): DatasourceOwnerDefinition {
  return DATASOURCE_OWNERS[datasource];
}

export function datasourceForOwner(owner: DatasourceOwner): Datasource {
  const found = DATASOURCES.find((d) => DATASOURCE_OWNERS[d].owner === owner);
  if (!found) {
    throw new Error(`No datasource is owned by "${owner}"`);
  }
  return found;
}

/**
 * Owners a runtime must ship a generated client for. `state` selects the
 * "instantiated" set (required + optional) or the "not-instantiated" set
 * (`not-used`), so Docker and health answer the same question the same way.
 */
export function ownersForRuntime(
  runtime: RuntimeId,
  state?: InstantiationState
): DatasourceOwner[] {
  const owners =
    state === 'not-instantiated'
      ? notUsedDatasources(runtime).map((d) => DATASOURCE_OWNERS[d].owner)
      : instantiatedDatasources(runtime).map((d) => DATASOURCE_OWNERS[d].owner);
  return DATASOURCE_OWNER_ORDER.filter((owner) => owners.includes(owner));
}

export function prismaProjectsForRuntime(runtime: RuntimeId): string[] {
  return ownersForRuntime(runtime).map(
    (owner) => DATASOURCE_OWNERS[datasourceForOwner(owner)].prismaProject
  );
}

export function generatedClientDirsForRuntime(runtime: RuntimeId): string[] {
  return ownersForRuntime(runtime).map(
    (owner) => DATASOURCE_OWNERS[datasourceForOwner(owner)].generatedClientDir
  );
}

export function prunedClientDirsForRuntime(runtime: RuntimeId): string[] {
  return ownersForRuntime(runtime, 'not-instantiated').map(
    (owner) => DATASOURCE_OWNERS[datasourceForOwner(owner)].generatedClientDir
  );
}

export function prismaGenerateScriptsForRuntime(runtime: RuntimeId): string[] {
  return ownersForRuntime(runtime)
    .map((owner) => DATASOURCE_OWNERS[datasourceForOwner(owner)])
    .filter((definition) => definition.status === 'implemented')
    .map((definition) => definition.generateScript);
}

