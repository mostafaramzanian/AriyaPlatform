/**
 * Phase ARCH-1.3: ONE requirement model, with explicit runtime semantics.
 *
 *   required  — INSTANTIATED and REQUIRED. The provider is constructed, a
 *               connection is expected, and a failed probe makes the runtime
 *               NOT READY (HTTP 503).
 *   optional  — INSTANTIATED-BUT-CONDITIONAL. The provider is constructed, but a
 *               connection is only attempted when the datasource's environment
 *               variable is configured. A missing ("not-configured") or failing
 *               ("failed") dependency is REPORTED in the readiness body and never
 *               blocks readiness. "optional" never means "not instantiated".
 *   not-used  — NOT INSTANTIATED. No provider, no import, no generated client
 *               artifact shipped, never probed. A runtime must not be able to
 *               reach a "not-used" datasource by accident.
 *
 * `not-used` is the only state that is allowed to omit a Prisma client from an
 * image; the Docker/prisma artifact boundary is derived from exactly that.
 */
export type Requirement = 'required' | 'optional' | 'not-used';

/** Derived from Requirement — never declared twice. */
export type InstantiationState = 'instantiated' | 'not-instantiated';

/** Outcome of a single dependency probe. */
export type ProbeStatus = 'ok' | 'failed' | 'not-configured' | 'not-used';

/** Declared so the policy projection can be emitted and re-read by tooling. */
export type RuntimePolicy = {
  datasources: Record<Datasource, Requirement>;
  infrastructure: Record<InfrastructureService, Requirement>;
};

