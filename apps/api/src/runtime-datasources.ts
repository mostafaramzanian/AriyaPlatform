export function runtimePolicy(runtime: RuntimeId): RuntimePolicy {
  return RUNTIME_DATASOURCE_MATRIX[runtime];
}

export function requiredDatasources(runtime: RuntimeId): Datasource[] {
  const policy = RUNTIME_DATASOURCE_MATRIX[runtime].datasources;
  return (Object.keys(policy) as Datasource[]).filter((d) => policy[d] === 'required');
}

export function optionalDatasources(runtime: RuntimeId): Datasource[] {
  const policy = RUNTIME_DATASOURCE_MATRIX[runtime].datasources;
  return (Object.keys(policy) as Datasource[]).filter((d) => policy[d] === 'optional');
}

export function notUsedDatasources(runtime: RuntimeId): Datasource[] {
  const policy = RUNTIME_DATASOURCE_MATRIX[runtime].datasources;
  return (Object.keys(policy) as Datasource[]).filter((d) => policy[d] === 'not-used');
}

/**
 * "instantiated" means required or optional: both states construct a provider and
 * therefore need the generated Prisma client artifact to exist. Only "not-used"
 * is not instantiated.
 */
export function datasourceInstantiation(
  runtime: RuntimeId,
  datasource: Datasource
): InstantiationState {
  return runtimePolicy(runtime).datasources[datasource] === 'not-used'
    ? 'not-instantiated'
    : 'instantiated';
}

export function instantiatedDatasources(runtime: RuntimeId): Datasource[] {
  return DATASOURCES.filter((d) => datasourceInstantiation(runtime, d) === 'instantiated');
}

